const KEY = 'ahli-finance-guide';

export function Guide() {
  const { dispatch, notify } = useStore();
  const [done, setDone] = useState(() => { try { return JSON.parse(localStorage.getItem(KEY)) || []; } catch { return []; } });
  useEffect(() => { try { localStorage.setItem(KEY, JSON.stringify(done)); } catch { /* ignore */ } }, [done]);
  const toggle = (i) => setDone((d) => (d.includes(i) ? d.filter((x) => x !== i) : [...d, i]));
  const pct = Math.round((done.length / STEPS.length) * 100);

  return (
    <div className="page">
      <div className="grid" style={{ gridTemplateColumns: '1fr 380px' }}>
        <div className="card" style={{ background: 'var(--ink)', color: '#fff', borderColor: 'var(--ink)' }}>
          <h3 style={{ color: '#fff', fontSize: 22 }}>أهلًا بك في تجربة النظام المالي</h3>
          <p style={{ color: '#CFCACF', lineHeight: 1.9, fontSize: 15 }}>
            هذه نسخة أولية للتجربة. <b style={{ color: '#fff' }}>دليل الحسابات حقيقي</b> ومنقول من «الرشيد»، أما الحركات والموظفون والمبالغ فهي <b style={{ color: '#fff' }}>بيانات تجريبية</b> لتجرّب عليها بحرية.
            اتبع الخطوات بالترتيب (نحو 25 دقيقة)، وعلّم على كل خطوة تنجح. لا تقلق من الخطأ — يمكنك إعادة كل شيء من الإعدادات.
          </p>
        </div>
        <div className="card">
          <h3>تقدّمك <small>{done.length} من {STEPS.length}</small></h3>
          <div className="track" style={{ height: 14 }}><i className="ok" style={{ width: pct + '%' }} /></div>
          <div style={{ fontSize: 36, fontWeight: 700, marginTop: 10 }} className="num">{pct}%</div>
          <div className="row" style={{ marginTop: 8 }}>
            <button className="btn sm" onClick={() => setDone([])}>تصفير التقدّم</button>
            <button className="btn sm" onClick={() => { if (confirm('إعادة البيانات التجريبية كما كانت؟')) { dispatch({ type: 'reset' }); notify('تمت إعادة البيانات التجريبية'); } }}>إعادة البيانات</button>
          </div>
        </div>
      </div>

      <div className="guide">
        {STEPS.map((st, i) => {
          const ok = done.includes(i);
          return (
            <div key={i} className={'g-step' + (ok ? ' done' : '')}>
              <button className="g-num" onClick={() => toggle(i)} title="علّم كمنجزة">{ok ? <Icon n="check" /> : i + 1}</button>
              <div className="g-body">
                <div className="g-head">
                  <h4>{st.t}</h4>
                  <span className="pill">{st.time}</span>
                  <span style={{ flex: 1 }} />
                  <a className="btn sm dark" href={'#/' + st.go}>افتح الصفحة <Icon n="left" s={14} /></a>
                </div>
                <ol>{st.do.map((d, k) => <li key={k}>{d}</li>)}</ol>
                <div className="g-ok"><b>النتيجة المتوقعة:</b> {st.ok}</div>
                <label className="row" style={{ gap: 8, marginTop: 10, fontWeight: 600 }}>
                  <input type="checkbox" checked={ok} onChange={() => toggle(i)} /> تمت الخطوة بنجاح
                </label>
              </div>
            </div>
          );
        })}
      </div>

      <div className="card">
        <h3>بعد التجربة — نحتاج رأيك في</h3>
        <div className="grid g2" style={{ lineHeight: 2 }}>
          <ul style={{ paddingRight: 20 }}>
            <li>هل ترتيب دليل الحسابات والمستويات واضح كما اعتدت؟</li>
            <li>هل إدخال القيد والسند أسرع أم أبطأ من «الرشيد»؟</li>
            <li>هل احتساب الرواتب والخصميات مطابق لطريقتكم؟</li>
          </ul>
          <ul style={{ paddingRight: 20 }}>
            <li>ما التقارير التي تستخدمونها ولا تجدونها هنا؟</li>
            <li>أسماء الحسابات الثمانية التي ليس لها اسم في الملف (34، 341، 41، 412، 413، 413001، 431، 431001).</li>
            <li>أي ملاحظة على الشكل أو الكلمات المستخدمة.</li>
          </ul>
        </div>
      </div>
    </div>
  );
}
